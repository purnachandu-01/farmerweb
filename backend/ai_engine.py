def predict_fair_price(crop_name, quantity=500, quality='Grade A', location='Kolar', season='Kharif Late'):
    """
    Simulates multi-factor regression model for predicting equitable farmgate corridors.
    Combines mandi baseline, seasonal festivity index, and produce quality rating.
    """
    crop_lower = crop_name.lower()
    
    # Base APMC Mandi price benchmarks (₹/kg)
    base_benchmarks = {
        'tomato': {'base': 28.0, 'variance': 0.18, 'demand': 'High', 'trend': '+14% upward'},
        'onion': {'base': 24.5, 'variance': 0.15, 'demand': 'High', 'trend': '+8% steady'},
        'potato': {'base': 21.0, 'variance': 0.12, 'demand': 'Medium', 'trend': '+4% balanced'},
        'chilli': {'base': 42.0, 'variance': 0.20, 'demand': 'High', 'trend': '+12% peak'},
        'turmeric': {'base': 85.0, 'variance': 0.15, 'demand': 'Medium-High', 'trend': '+6% strong'},
        'paddy': {'base': 38.0, 'variance': 0.10, 'demand': 'Medium', 'trend': '+3% stable'},
        'rice': {'base': 38.0, 'variance': 0.10, 'demand': 'Medium', 'trend': '+3% stable'}
    }

    matched_key = next((k for k in base_benchmarks if k in crop_lower), 'tomato')
    meta = base_benchmarks[matched_key]
    base_price = meta['base']

    # Quality Grade multiplier
    quality_mult = 1.0
    if 'organic' in quality.lower():
        quality_mult = 1.22
    elif 'grade a' in quality.lower():
        quality_mult = 1.08
    elif 'grade b' in quality.lower():
        quality_mult = 0.92

    # Location freight coefficient
    loc_mult = 1.0
    if 'kolar' in location.lower():
        loc_mult = 1.04  # High urban proximity advantage
    elif 'nashik' in location.lower():
        loc_mult = 1.02

    adjusted_base = base_price * quality_mult * loc_mult
    min_price = round(adjusted_base)
    max_price = round(adjusted_base * (1 + meta['variance']))

    # Historical & forecasted corridor points
    historical_trend = [
        {'day': 'Day -14', 'mandiPrice': min_price - 5, 'fairCorridor': min_price - 3},
        {'day': 'Day -10', 'mandiPrice': min_price - 4, 'fairCorridor': min_price - 2},
        {'day': 'Day -7',  'mandiPrice': min_price - 3, 'fairCorridor': min_price},
        {'day': 'Day -3',  'mandiPrice': min_price - 1, 'fairCorridor': min_price + 2},
        {'day': 'Today',   'mandiPrice': min_price,     'fairCorridor': round((min_price + max_price) / 2)},
        {'day': 'Day +3 (Forecast)', 'mandiPrice': min_price + 1, 'fairCorridor': max_price - 1},
        {'day': 'Day +7 (Forecast)', 'mandiPrice': min_price + 2, 'fairCorridor': max_price}
    ]

    return {
        'crop': crop_name,
        'quantity': quantity,
        'quality': quality,
        'location': location,
        'season': season,
        'currency': '₹',
        'unit': 'kg',
        'suggestedMin': min_price,
        'suggestedMax': max_price,
        'confidence': '91%',
        'demandLevel': meta['demand'],
        'marketTrend': meta['trend'],
        'factors': [
            {'name': 'Seasonal Festivity & Mandi Arrival Flow', 'weight': '+12%', 'impact': 'positive'},
            {'name': 'Regional Wholesale Shortfall (APMC Catchment)', 'weight': '+8%', 'impact': 'positive'},
            {'name': f'Quality Grade Premium ({quality})', 'weight': '+5%' if quality_mult >= 1.0 else '-8%', 'impact': 'positive' if quality_mult >= 1.0 else 'negative'},
            {'name': 'Inter-district Transport Fuel Index', 'weight': '-3%', 'impact': 'negative'}
        ],
        'historicalTrend': historical_trend,
        'disclaimer': 'Illustrative prototype result generated by Farm2Fair AI engine for SIH 2026.'
    }


def evaluate_storage_advice(crop_name, quantity=1000, current_price=28.0, storage_cost_per_day=0.15, storage_days=20):
    """
    Evaluates net profitability of holding produce in cold storage vs immediate selling.
    """
    total_storage_cost = storage_cost_per_day * storage_days * quantity
    expected_surge_percent = 0.18  # +18% price surge in 3 weeks
    projected_future_price = current_price * (1 + expected_surge_percent)
    gross_future_rev = projected_future_price * quantity
    current_rev = current_price * quantity
    net_gain = gross_future_rev - total_storage_cost - current_rev

    if net_gain > 1500:
        recommendation = 'Consider Short-Term Cold Storage (15-25 Days)'
        rationale = f'Expected mandi arrivals will dip in 3 weeks, yielding a projected net upside of ₹{round(net_gain):,} after storage rent.'
        risk_level = 'Moderate (Cold-chain maintenance required)'
    else:
        recommendation = 'Consider Selling Fresh Produce Now'
        rationale = 'High storage rent or potential shrinkage outweighs projected price appreciation. Immediate dispatch recommended.'
        risk_level = 'Low'

    return {
        'crop': crop_name,
        'quantity': quantity,
        'currentPrice': current_price,
        'projectedFuturePrice': round(projected_future_price, 2),
        'totalStorageCost': round(total_storage_cost, 2),
        'estimatedNetGain': round(net_gain, 2),
        'recommendation': recommendation,
        'rationale': rationale,
        'riskLevel': risk_level,
        'confidence': '84% (Prototype Model)'
    }
